"""Generates tests/cpp/GzipVectors.h: (compressed, expected) gzip vectors.

All compressed bytes come from CPython's zlib (independent of the C++
inflater under test). Regeneration is deterministic (fixed seeds/levels).
Large expectations are pinned by (length, crc32, head/tail bytes) instead
of full arrays to keep the header small.
"""

import os
import random
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "tests", "cpp", "GzipVectors.h")


def gzip_bytes(payload: bytes, level=6, strategy=zlib.Z_DEFAULT_STRATEGY) -> bytes:
    comp = zlib.compressobj(level, zlib.DEFLATED, 31, 9, strategy)
    return comp.compress(payload) + comp.flush()


def carray(name, data: bytes) -> str:
    body = ", ".join(str(b) for b in data)
    return "static const unsigned char %s[] = {%s};\nstatic const unsigned %sLen = %d;\n" % (
        name, body if body else "0", name, len(data))


def main():
    rng = random.Random(20261013)
    cases = {}
    cases["empty"] = (gzip_bytes(b""), b"")
    cases["hello"] = (gzip_bytes(b"hello world\n" * 50), b"hello world\n" * 50)
    cases["bytes256"] = (gzip_bytes(bytes(range(256)) * 4), bytes(range(256)) * 4)
    cases["fixed"] = (
        gzip_bytes(b"The quick brown fox jumps over the lazy dog. " * 40, 6, zlib.Z_FIXED),
        b"The quick brown fox jumps over the lazy dog. " * 40)
    # FNAME-carrying member exercises the gzip header skip paths.
    import io as _io
    import gzip as _gzip
    _buf = _io.BytesIO()
    with _gzip.GzipFile(filename="schematic.litematic", mode="wb", fileobj=_buf, mtime=1720000000) as _gz:
        _gz.write(b"named-member payload")
    cases["named"] = (_buf.getvalue(), b"named-member payload")
    # NOTE: raw-stored blocks are hand-built in TestGzip.cpp (with its own
    # CRC32), so no level-0 vector is embedded here.
    cases["random8k"] = (gzip_bytes(bytes(rng.randrange(256) for _ in range(8192))), None)
    text = ("Lorem ipsum dolor sit amet, consectetur adipiscing elit. " * 2000).encode()
    cases["text100k"] = (gzip_bytes(text), text)
    cases["bomb"] = (gzip_bytes(bytes(2 * 1024 * 1024)), None)

    # Rebuild random8k expected deterministically for meta pinning.
    rng2 = random.Random(20261013)
    random8k_expected = bytes(rng2.randrange(256) for _ in range(8192))

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("// GENERATED by tools/gen_gzip_vectors.py — do not edit by hand.\n")
        f.write("#pragma once\n\n#include <cstddef>\n\n")
        for name, (comp, exp) in cases.items():
            f.write(carray("kGz_" + name, comp))
            if exp is not None and len(exp) <= 4096:
                f.write(carray("kRaw_" + name, exp))
            f.write("\n")
        f.write("struct GzipMetaExpectation {\n")
        f.write("    const char* name;\n    unsigned length;\n    unsigned crc;\n")
        f.write("    unsigned char head[16];\n    unsigned char tail[16];\n};\n\n")
        f.write("static const GzipMetaExpectation kGzipMeta[] = {\n")
        for name in ("random8k", "text100k", "bomb"):
            exp = {
                "random8k": random8k_expected,
                "text100k": text,
                "bomb": bytes(2 * 1024 * 1024),
            }[name]
            head = exp[:16] + bytes(max(0, 16 - len(exp)))
            tail = exp[-16:] if len(exp) >= 16 else bytes(16 - len(exp)) + exp
            f.write('    {"%s", %d, 0x%08XU, {%s}, {%s}},\n' % (
                name, len(exp), zlib.crc32(exp) & 0xFFFFFFFF,
                ", ".join(str(b) for b in head), ", ".join(str(b) for b in tail)))
        f.write("};\n")
    print("wrote %s" % OUT)


if __name__ == "__main__":
    main()
